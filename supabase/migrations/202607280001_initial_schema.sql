-- Hanyu initial Supabase schema
-- Auth, RLS, and user-owned learning tables.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.user_settings (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  theme text not null default 'light' check (theme in ('light', 'dark', 'system')),
  current_level integer not null default 2 check (current_level between 1 and 6),
  cards_per_day integer not null default 20 check (cards_per_day between 1 and 100),
  max_reviews_per_session integer not null default 100 check (max_reviews_per_session between 1 and 300),
  card_order text not null default 'due' check (card_order in ('due', 'frequency')),
  ai_provider text not null default 'none' check (ai_provider in ('none', 'deepseek', 'gemini')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.words (
  id bigint generated by default as identity primary key,
  hanzi text not null,
  pinyin text not null,
  meaning_en text not null,
  meaning_es text,
  hsk_level integer not null check (hsk_level between 1 and 6),
  pos text,
  frequency integer,
  unique (hanzi, hsk_level)
);

create table if not exists public.grammar_points (
  id bigint generated by default as identity primary key,
  hsk_level integer not null check (hsk_level between 1 and 6),
  title text not null,
  explanation text not null,
  examples jsonb not null default '[]'::jsonb,
  order_idx integer,
  created_at timestamptz not null default now()
);

create table if not exists public.srs_cards (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  word_id bigint not null references public.words(id) on delete cascade,
  ease_factor numeric not null default 2.5,
  interval_days integer not null default 0,
  repetitions integer not null default 0,
  next_review_at timestamptz not null default now(),
  last_reviewed_at timestamptz,
  status text not null default 'new' check (status in ('new', 'learning', 'review', 'mastered')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, word_id)
);

create table if not exists public.review_log (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  card_id uuid not null references public.srs_cards(id) on delete cascade,
  reviewed_at timestamptz not null default now(),
  quality integer not null check (quality between 0 and 5),
  time_ms integer
);

create table if not exists public.user_stats (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  date date not null,
  cards_reviewed integer not null default 0,
  cards_new integer not null default 0,
  exercises_done integer not null default 0,
  readings_done integer not null default 0,
  time_spent_ms integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, date)
);

create table if not exists public.generated_exercises (
  id uuid primary key default gen_random_uuid(),
  type text not null check (type in ('fill_blank', 'multiple_choice', 'reorder', 'dictation', 'matching')),
  hsk_level integer not null check (hsk_level between 1 and 6),
  prompt jsonb not null,
  answer jsonb not null,
  source_model text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.exercise_attempts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  exercise_id uuid references public.generated_exercises(id) on delete set null,
  submitted_answer jsonb not null,
  is_correct boolean not null,
  feedback jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.generated_readings (
  id uuid primary key default gen_random_uuid(),
  hsk_level integer not null check (hsk_level between 1 and 6),
  format text not null check (format in ('short_text', 'story', 'dialogue')),
  title text not null,
  content text not null,
  pinyin_text text,
  questions jsonb not null default '[]'::jsonb,
  source_model text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.reading_attempts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  reading_id uuid not null references public.generated_readings(id) on delete cascade,
  answers jsonb not null,
  score integer not null,
  total integer not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_words_hsk_level on public.words(hsk_level);
create index if not exists idx_words_hanzi on public.words(hanzi);
create unique index if not exists idx_words_unique_entry
  on public.words(hanzi, pinyin, meaning_en, hsk_level);

create index if not exists idx_grammar_hsk_level on public.grammar_points(hsk_level);
create unique index if not exists idx_grammar_unique_entry
  on public.grammar_points(hsk_level, title);

create index if not exists idx_srs_cards_user_next_review on public.srs_cards(user_id, next_review_at);
create index if not exists idx_srs_cards_user_status on public.srs_cards(user_id, status);

create index if not exists idx_review_log_user_reviewed_at on public.review_log(user_id, reviewed_at desc);
create index if not exists idx_user_stats_user_date on public.user_stats(user_id, date desc);

create index if not exists idx_generated_exercises_level_type on public.generated_exercises(hsk_level, type);
create index if not exists idx_generated_exercises_created_by on public.generated_exercises(created_by);
create unique index if not exists idx_generated_exercises_seed_unique
  on public.generated_exercises(type, hsk_level, prompt, answer, coalesce(source_model, ''));

create index if not exists idx_exercise_attempts_user_created on public.exercise_attempts(user_id, created_at desc);
create index if not exists idx_generated_readings_level_format on public.generated_readings(hsk_level, format);
create index if not exists idx_generated_readings_created_by on public.generated_readings(created_by);
create index if not exists idx_reading_attempts_user_created on public.reading_attempts(user_id, created_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_profiles_updated_at on public.profiles;
create trigger set_profiles_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

drop trigger if exists set_user_settings_updated_at on public.user_settings;
create trigger set_user_settings_updated_at
before update on public.user_settings
for each row execute function public.set_updated_at();

drop trigger if exists set_srs_cards_updated_at on public.srs_cards;
create trigger set_srs_cards_updated_at
before update on public.srs_cards
for each row execute function public.set_updated_at();

drop trigger if exists set_user_stats_updated_at on public.user_stats;
create trigger set_user_stats_updated_at
before update on public.user_stats
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id)
  values (new.id)
  on conflict (id) do nothing;

  insert into public.user_settings (user_id)
  values (new.id)
  on conflict (user_id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();


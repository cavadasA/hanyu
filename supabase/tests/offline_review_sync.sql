-- offline_review_sync.sql
-- Tests for the idempotent six-argument review_flashcard RPC.
-- Wraps everything in a single transaction and rolls back — safe to run against any database.
--
-- Covers five cases:
--   1. Matching expected_version → outcome='applied', version=1, one log row
--   2. Same client review_id again → outcome='duplicate', one log/stat total
--   3. Stale expected_version → outcome='conflict', no mutation
--   4a. Invalid quality (6) → exception raised
--   4b. Another user's card → exception raised ('Card not found')
--   5. Old three-argument RPC still succeeds

begin;

-- ───────────────────────────────────────────────
-- Setup
-- ───────────────────────────────────────────────

-- Create two test users (trigger auto-creates public.profiles + user_settings rows)
insert into auth.users (id, aud, role, email, created_at, updated_at)
values
  ('a0000000-0000-0000-0000-000000000001', 'authenticated', 'authenticated',
   'task2test1@example.com', now(), now()),
  ('a0000000-0000-0000-0000-000000000002', 'authenticated', 'authenticated',
   'task2test2@example.com', now(), now());

-- Create a word (id is GENERATED BY DEFAULT, so explicit value is allowed)
insert into public.words (id, hanzi, pinyin, meaning_en, hsk_level)
values (99901, '测', 'cè', 'test-task2', 1);

-- One card per user
insert into public.srs_cards (id, user_id, word_id)
values
  ('b0000000-0000-0000-0000-000000000001',
   'a0000000-0000-0000-0000-000000000001', 99901),
  ('b0000000-0000-0000-0000-000000000002',
   'a0000000-0000-0000-0000-000000000002', 99901);

-- Simulate being logged in as user 1 for the rest of this transaction
set local "request.jwt.claim.sub" = 'a0000000-0000-0000-0000-000000000001';

-- ───────────────────────────────────────────────
-- Case 1: matching expected_version returns 'applied', version increments to 1
-- ───────────────────────────────────────────────
do $$
declare
  v_outcome text;
  v_version bigint;
  v_interval integer;
  v_status text;
  v_log_count bigint;
begin
  select outcome, version, "interval", status
  into v_outcome, v_version, v_interval, v_status
  from public.review_flashcard(
    'b0000000-0000-0000-0000-000000000001'::uuid,  -- card_id
    4,                                               -- quality
    1000,                                            -- time_ms
    'c0000000-0000-0000-0000-000000000001'::uuid,  -- review_id
    now(),                                           -- reviewed_at
    0::bigint                                        -- expected_version (matches default 0)
  );

  if v_outcome <> 'applied' then
    raise exception 'Case 1 FAILED: expected outcome=applied, got=%', v_outcome;
  end if;

  if v_version <> 1 then
    raise exception 'Case 1 FAILED: expected version=1, got=%', v_version;
  end if;

  if v_interval is null then
    raise exception 'Case 1 FAILED: interval is null';
  end if;

  if v_status is null then
    raise exception 'Case 1 FAILED: status is null';
  end if;

  -- Confirm exactly one review_log row with this client_review_id
  select count(*) into v_log_count
  from public.review_log
  where user_id = 'a0000000-0000-0000-0000-000000000001'
    and client_review_id = 'c0000000-0000-0000-0000-000000000001';

  if v_log_count <> 1 then
    raise exception 'Case 1 FAILED: expected 1 log row, got=%', v_log_count;
  end if;
end $$;

-- ───────────────────────────────────────────────
-- Case 2: same review_id → duplicate, one log/stat total
-- ───────────────────────────────────────────────
do $$
declare
  v_outcome text;
  v_version bigint;
  v_log_count bigint;
  v_stats_reviewed integer;
begin
  -- Retry the exact same review event
  select outcome, version
  into v_outcome, v_version
  from public.review_flashcard(
    'b0000000-0000-0000-0000-000000000001'::uuid,
    4,
    1000,
    'c0000000-0000-0000-0000-000000000001'::uuid,  -- same review_id
    now(),
    1::bigint
  );

  if v_outcome <> 'duplicate' then
    raise exception 'Case 2 FAILED: expected outcome=duplicate, got=%', v_outcome;
  end if;

  -- Should return current authoritative version (1 after Case 1)
  if v_version <> 1 then
    raise exception 'Case 2 FAILED: expected version=1, got=%', v_version;
  end if;

  -- Still only one log row (no second insert)
  select count(*) into v_log_count
  from public.review_log
  where user_id = 'a0000000-0000-0000-0000-000000000001'
    and client_review_id = 'c0000000-0000-0000-0000-000000000001';

  if v_log_count <> 1 then
    raise exception 'Case 2 FAILED: expected 1 log row total, got=%', v_log_count;
  end if;

  -- Stats should show exactly 1 review (not 2)
  select coalesce(sum(cards_reviewed), 0)::integer into v_stats_reviewed
  from public.user_stats
  where user_id = 'a0000000-0000-0000-0000-000000000001';

  if v_stats_reviewed <> 1 then
    raise exception 'Case 2 FAILED: expected 1 stat increment total, got=%', v_stats_reviewed;
  end if;
end $$;

-- ───────────────────────────────────────────────
-- Case 3: stale expected_version → conflict, no mutation
-- ───────────────────────────────────────────────
do $$
declare
  v_outcome text;
  v_version bigint;
  v_log_count bigint;
begin
  -- Card is now at version=1; pass expected_version=0 (stale)
  select outcome, version
  into v_outcome, v_version
  from public.review_flashcard(
    'b0000000-0000-0000-0000-000000000001'::uuid,
    4,
    1000,
    'c0000000-0000-0000-0000-000000000002'::uuid,  -- fresh review_id, not a duplicate
    now(),
    0::bigint  -- stale: actual version is 1
  );

  if v_outcome <> 'conflict' then
    raise exception 'Case 3 FAILED: expected outcome=conflict, got=%', v_outcome;
  end if;

  -- Returns current version (1) without mutation
  if v_version <> 1 then
    raise exception 'Case 3 FAILED: expected version=1 (no mutation), got=%', v_version;
  end if;

  -- No second log row was created (log count still 1 from Case 1)
  select count(*) into v_log_count
  from public.review_log
  where user_id = 'a0000000-0000-0000-0000-000000000001';

  if v_log_count <> 1 then
    raise exception 'Case 3 FAILED: expected 1 log row total (no new insert on conflict), got=%', v_log_count;
  end if;
end $$;

-- ───────────────────────────────────────────────
-- Case 4a: invalid quality (6) → exception
-- ───────────────────────────────────────────────
do $$
begin
  begin
    perform public.review_flashcard(
      'b0000000-0000-0000-0000-000000000001'::uuid,
      6,       -- invalid: must be 0..5
      1000,
      'c0000000-0000-0000-0000-000000000099'::uuid,
      now(),
      1::bigint
    );
    -- If we reach here, the function did NOT raise — that is a test failure
    raise exception 'Case 4a FAILED: expected exception for quality=6, none raised';
  exception when others then
    if sqlerrm like 'Case 4a FAILED%' then
      raise;  -- propagate the test-failure exception
    end if;
    -- Any other exception means the RPC correctly rejected the call
  end;
end $$;

-- ───────────────────────────────────────────────
-- Case 4b: another user's card → exception ('Card not found')
-- ───────────────────────────────────────────────
do $$
begin
  begin
    -- User 1 is authenticated but card b...002 belongs to user 2
    perform public.review_flashcard(
      'b0000000-0000-0000-0000-000000000002'::uuid,
      4,
      1000,
      'c0000000-0000-0000-0000-000000000098'::uuid,
      now(),
      0::bigint
    );
    raise exception 'Case 4b FAILED: expected exception for wrong-user card, none raised';
  exception when others then
    if sqlerrm like 'Case 4b FAILED%' then
      raise;
    end if;
  end;
end $$;

-- ───────────────────────────────────────────────
-- Case 5: old three-argument RPC still succeeds
-- ───────────────────────────────────────────────
do $$
declare
  v_interval integer;
  v_status text;
  v_next_review date;
begin
  select "interval", status, next_review
  into v_interval, v_status, v_next_review
  from public.review_flashcard(
    'b0000000-0000-0000-0000-000000000001'::uuid,
    4,
    500
  );

  if v_interval is null then
    raise exception 'Case 5 FAILED: three-arg RPC returned null interval';
  end if;

  if v_status is null then
    raise exception 'Case 5 FAILED: three-arg RPC returned null status';
  end if;

  if v_next_review is null then
    raise exception 'Case 5 FAILED: three-arg RPC returned null next_review';
  end if;
end $$;

rollback;
